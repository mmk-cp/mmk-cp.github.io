import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = process.cwd();
const source = (path) => resolve(root, path);

const mimeTypes = {
  '.png': 'image/png',
  '.svg': 'image/svg+xml'
};

function extension(path) {
  return path.slice(path.lastIndexOf('.'));
}

async function dataUri(path) {
  const data = await readFile(source(path));
  const mimeType = mimeTypes[extension(path)];
  if (!mimeType) throw new Error(`Unsupported asset type: ${path}`);
  return `data:${mimeType};base64,${data.toString('base64')}`;
}

const [sourceHtml, styles, script] = await Promise.all([
  readFile(source('index.html'), 'utf8'),
  readFile(source('styles.css'), 'utf8'),
  readFile(source('script.js'), 'utf8')
]);

let output = sourceHtml
  .replace('<link rel="stylesheet" href="styles.css">', `<style>\n${styles}\n</style>`)
  .replace('<script src="script.js" defer></script>', `<script>\n${script}\n</script>`);

const assets = [
  'assets/img/favicon.svg',
  'assets/img/profile.png',
  'assets/certificates/java-se-8.png',
  'assets/certificates/network-plus.png'
];

for (const asset of assets) {
  output = output.replaceAll(asset, await dataUri(asset));
}

output = output.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build-single-file.mjs. Do not edit this file directly. -->');
await writeFile(source('resume-single-file.html'), output);
console.log('Generated resume-single-file.html');
